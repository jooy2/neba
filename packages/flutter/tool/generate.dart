// Writes the two files in this package that are lists of other files.
//
//   dart run tool/generate.dart          writes them
//   dart run tool/generate.dart --check  fails if either is out of date
//
// `lib/neba.dart` is the barrel: one export per widget file under
// `lib/src/components/`, plus the theme and the shared types. A widget that
// is written and never exported is a widget nobody can use, and nothing else
// would notice.
//
// `example/lib/demos/registry.dart` maps every demo to the key the
// documentation site asks for it by: `example/lib/demos/text_field/sizes.dart`
// declaring `TextFieldSizes` is `'text-field/sizes'`, which is the React
// demo's path, so one `<Demo src="text-field/sizes">` names both.
//
// `test/package/generated_test.dart` runs this with `--check`.

import 'dart:convert';
import 'dart:io';

const String _header = '// Generated by `tool/generate.dart`. Do not edit by hand.\n';

/// The files the barrel exports besides the widgets, in the order they appear.
const List<String> _foundation = <String>[
  'src/theme/scale.dart',
  'src/theme/theme.dart',
  'src/theme/tokens.dart',
  'src/types.dart',
];

Future<void> main(List<String> arguments) async {
  final bool check = arguments.contains('--check');
  final Map<String, String> outputs = <String, String>{
    'lib/neba.dart': await _format('lib/neba.dart', _barrel()),
  };

  if (Directory('example/lib/demos').existsSync()) {
    outputs['example/lib/demos/registry.dart'] = await _format(
      'example/lib/demos/registry.dart',
      _registry(),
    );
  }

  final List<String> stale = <String>[];

  for (final MapEntry<String, String> output in outputs.entries) {
    final File file = File(output.key);
    final String current = file.existsSync() ? file.readAsStringSync() : '';

    if (current == output.value) {
      continue;
    }

    if (check) {
      stale.add(output.key);
    } else {
      file.writeAsStringSync(output.value);
      stdout.writeln('wrote ${output.key}');
    }
  }

  if (stale.isNotEmpty) {
    stderr.writeln('Out of date: ${stale.join(', ')}. Run `dart run tool/generate.dart`.');
    exitCode = 1;
  }
}

String _barrel() {
  final List<String> widgets =
      Directory('lib/src/components')
          .listSync(recursive: true)
          .whereType<File>()
          .map((File file) => _relative(file.path, 'lib/'))
          .where((String path) => RegExp(r'/neba_[a-z0-9_]+\.dart$').hasMatch(path))
          .toList()
        ..sort();
  final List<String> exports = <String>[...widgets, ..._foundation]..sort();

  return '''
$_header
/// Neba UI for Flutter: the components and the acrylic design language of the
/// React package `neba`, built on `package:flutter/widgets.dart` alone.
///
/// Nothing here imports `package:flutter/material.dart` or
/// `package:flutter/cupertino.dart`, which is what lets a Neba widget sit
/// inside a Material app, a Cupertino app or a bare [WidgetsApp] without
/// bringing a second design system in behind it.
///
/// A widget works with no setup: with nothing above it, the colours follow
/// the platform's brightness. [NebaProvider] sets defaults and pins the colour
/// scheme for a subtree.
///
/// ```dart
/// import 'package:neba/neba.dart';
///
/// NebaProvider(
///   defaults: const NebaDefaults(size: NebaSize.lg),
///   child: app,
/// )
/// ```
library;

${exports.map((String path) => "export '$path';").join('\n')}
''';
}

String _registry() {
  final List<_Demo> demos = <_Demo>[];
  final RegExp declaration = RegExp(
    r'^class (\w+) extends State(?:less|ful)Widget',
    multiLine: true,
  );

  for (final FileSystemEntity entity in Directory('example/lib/demos').listSync(recursive: true)) {
    if (entity is! File || !entity.path.endsWith('.dart')) {
      continue;
    }

    final String path = _relative(entity.path, 'example/lib/demos/');
    final List<String> parts = path.split('/');

    if (parts.length != 2) {
      continue;
    }

    final RegExpMatch? match = declaration.firstMatch(entity.readAsStringSync());

    if (match == null) {
      continue;
    }

    final String key =
        '${parts[0].replaceAll('_', '-')}/${parts[1].replaceAll('.dart', '').replaceAll('_', '-')}';
    demos.add(_Demo(key: key, path: path, className: match.group(1)!));
  }

  demos.sort((_Demo a, _Demo b) => a.key.compareTo(b.key));

  final String imports = demos
      .map((_Demo demo) => "import 'package:neba_example/demos/${demo.path}';")
      .join('\n');
  final String entries = demos
      .map((_Demo demo) => "  '${demo.key}': ${demo.className}.new,")
      .join('\n');

  return '''
$_header
/// Every demo the gallery can show, under the key the documentation site asks
/// for it by.
library;

import 'package:flutter/widgets.dart';

$imports

/// The demos, by key.
const Map<String, Widget Function()> demos = <String, Widget Function()>{
$entries
};
''';
}

String _relative(String path, String root) {
  final String normal = path.replaceAll(r'\', '/');
  final int index = normal.indexOf(root);

  return index == -1 ? normal : normal.substring(index + root.length);
}

/// Runs [source] through `dart format`, so the output follows the page width in
/// `analysis_options.yaml` and a formatter run in CI leaves it alone.
Future<String> _format(String path, String source) async {
  final Process process = await Process.start(Platform.resolvedExecutable, <String>[
    'format',
    '--stdin-name=$path',
  ]);
  process.stdin.write(source);
  await process.stdin.close();

  final String output = await process.stdout.transform(utf8.decoder).join();
  final String errors = await process.stderr.transform(utf8.decoder).join();

  if (await process.exitCode != 0) {
    throw StateError('dart format failed on $path:\n$errors');
  }

  return output;
}

class _Demo {
  const _Demo({required this.key, required this.path, required this.className});

  final String key;
  final String path;
  final String className;
}
