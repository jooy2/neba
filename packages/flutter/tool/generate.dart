// Writes the two files in this package that are lists of other files.
//
//   dart run tool/generate.dart          writes them
//   dart run tool/generate.dart --check  fails if either is out of date
//
// `lib/neba.dart` is the barrel: one export per widget file under
// `lib/src/components/`, plus the theme and the shared types. A widget that
// is written and never exported is a widget nobody can use, and nothing else
// would notice.
//
// `example/lib/demos/registry.dart` maps every demo to the key the
// documentation site asks for it by: `example/lib/demos/text_field/sizes.dart`
// declaring `TextFieldSizes` is `'text-field/sizes'`, which is the React
// demo's path, so one `<Demo src="text-field/sizes">` names both.
//
// `lib/src/internal/messages_en.dart`, `lib/src/locales/*.dart` and
// `lib/locales.dart` are the words the library says on its own behalf, read out
// of the React package's tables: English from `src/internal/i18n.ts` and every
// other language from `src/locales/*.ts`. Generated rather than translated
// twice, so a string changed on the React side is a string changed here, and a
// key that exists there and not here fails the check below.
//
// `test/package/generated_test.dart` runs this with `--check`.

import 'dart:convert';
import 'dart:io';

const String _header = '// Generated by `tool/generate.dart`. Do not edit by hand.\n';

/// The files the barrel exports besides the widgets, in the order they appear.
const List<String> _foundation = <String>[
  'src/theme/scale.dart',
  'src/theme/theme.dart',
  'src/theme/tokens.dart',
  'src/types.dart',
];

Future<void> main(List<String> arguments) async {
  final bool check = arguments.contains('--check');
  final Map<String, String> outputs = <String, String>{
    'lib/neba.dart': await _format('lib/neba.dart', _barrel()),
  };

  for (final MapEntry<String, String> generated in _messages().entries) {
    outputs[generated.key] = await _format(generated.key, generated.value);
  }

  if (Directory('example/lib/demos').existsSync()) {
    outputs['example/lib/demos/registry.dart'] = await _format(
      'example/lib/demos/registry.dart',
      _registry(),
    );
  }

  final List<String> stale = <String>[];

  // A language the React package no longer has leaves its Dart file behind.
  for (final File orphan in _files('lib/src/locales')) {
    final String path = orphan.path.replaceAll(r'\\', '/');

    if (!outputs.containsKey(path)) {
      if (check) {
        stale.add(path);
      } else {
        orphan.deleteSync();
        stdout.writeln('deleted $path');
      }
    }
  }

  for (final MapEntry<String, String> output in outputs.entries) {
    final File file = File(output.key);
    final String current = file.existsSync() ? file.readAsStringSync() : '';

    if (current == output.value) {
      continue;
    }

    if (check) {
      stale.add(output.key);
    } else {
      file.parent.createSync(recursive: true);
      file.writeAsStringSync(output.value);
      stdout.writeln('wrote ${output.key}');
    }
  }

  if (stale.isNotEmpty) {
    stderr.writeln('Out of date: ${stale.join(', ')}. Run `dart run tool/generate.dart`.');
    exitCode = 1;
  }
}

String _barrel() {
  final List<String> widgets =
      Directory('lib/src/components')
          .listSync(recursive: true)
          .whereType<File>()
          .map((File file) => _relative(file.path, 'lib/'))
          .where((String path) => RegExp(r'/neba_[a-z0-9_]+\.dart$').hasMatch(path))
          .toList()
        ..sort();
  final List<String> exports = <String>[...widgets, ..._foundation]..sort();

  return '''
$_header
/// Neba UI for Flutter: the components and the acrylic design language of the
/// React package `neba`, built on `package:flutter/widgets.dart` alone.
///
/// Nothing here imports `package:flutter/material.dart` or
/// `package:flutter/cupertino.dart`, which is what lets a Neba widget sit
/// inside a Material app, a Cupertino app or a bare [WidgetsApp] without
/// bringing a second design system in behind it.
///
/// A widget works with no setup: with nothing above it, the colours follow
/// the platform's brightness. [NebaProvider] sets defaults and pins the colour
/// scheme for a subtree.
///
/// ```dart
/// import 'package:neba/neba.dart';
///
/// NebaProvider(
///   defaults: const NebaDefaults(size: NebaSize.lg),
///   child: app,
/// )
/// ```
library;

${exports.map((String path) => "export '$path';").join('\n')}
''';
}

String _registry() {
  final List<_Demo> demos = <_Demo>[];

  for (final FileSystemEntity entity in Directory('example/lib/demos').listSync(recursive: true)) {
    if (entity is! File || !entity.path.endsWith('.dart')) {
      continue;
    }

    final String path = _relative(entity.path, 'example/lib/demos/');
    final List<String> parts = path.split('/');

    if (parts.length != 2) {
      continue;
    }

    final String file = parts[1].replaceAll('.dart', '');
    // The demo is the class its path names, `button/icons.dart` declaring
    // `ButtonIcons`, and not whichever widget the file happens to declare
    // first: a demo with an icon of its own above it was registered as the
    // icon, and a gallery test cannot tell, because the icon builds too.
    final String className = '${parts[0]}_$file'
        .split('_')
        .map((String word) => word.isEmpty ? word : word[0].toUpperCase() + word.substring(1))
        .join();
    final RegExp declaration = RegExp(
      '^class $className extends State(?:less|ful)Widget',
      multiLine: true,
    );

    if (!declaration.hasMatch(entity.readAsStringSync())) {
      throw StateError('example/lib/demos/$path declares no widget named $className');
    }

    final String key = '${parts[0].replaceAll('_', '-')}/${file.replaceAll('_', '-')}';
    demos.add(_Demo(key: key, path: path, className: className));
  }

  demos.sort((_Demo a, _Demo b) => a.key.compareTo(b.key));

  final String imports = demos
      .map((_Demo demo) => "import 'package:neba_example/demos/${demo.path}';")
      .join('\n');
  final String entries = demos
      .map((_Demo demo) => "  '${demo.key}': ${demo.className}.new,")
      .join('\n');

  return '''
$_header
/// Every demo the gallery can show, under the key the documentation site asks
/// for it by.
library;

import 'package:flutter/widgets.dart';

$imports

/// The demos, by key.
const Map<String, Widget Function()> demos = <String, Widget Function()>{
$entries
};
''';
}

String _relative(String path, String root) {
  final String normal = path.replaceAll(r'\', '/');
  final int index = normal.indexOf(root);

  return index == -1 ? normal : normal.substring(index + root.length);
}

/// Runs [source] through `dart format`, so the output follows the page width in
/// `analysis_options.yaml` and a formatter run in CI leaves it alone.
Future<String> _format(String path, String source) async {
  final Process process = await Process.start(Platform.resolvedExecutable, <String>[
    'format',
    '--stdin-name=$path',
  ]);
  process.stdin.write(source);
  await process.stdin.close();

  final String output = await process.stdout.transform(utf8.decoder).join();
  final String errors = await process.stderr.transform(utf8.decoder).join();

  if (await process.exitCode != 0) {
    throw StateError('dart format failed on $path:\n$errors');
  }

  return output;
}

class _Demo {
  const _Demo({required this.key, required this.path, required this.className});

  final String key;
  final String path;
  final String className;
}

Iterable<File> _files(String directory) {
  final Directory folder = Directory(directory);

  return folder.existsSync()
      ? folder.listSync().whereType<File>().where((File file) => file.path.endsWith('.dart'))
      : const <File>[];
}

/// The React package's source, which the message tables are read from.
const String _react = '../react/src';

/// Every generated message file, by path.
Map<String, String> _messages() {
  // Before anything is formatted: `dart format` finds the page width in
  // `analysis_options.yaml` by walking up from the file's folder, and a folder
  // that does not exist yet has nothing to walk up from.
  Directory('lib/src/locales').createSync(recursive: true);

  final String i18n = File('$_react/internal/i18n.ts').readAsStringSync();
  final Map<String, Object> english = <String, Object>{};

  // `byNamespace` names each namespace's table: `action: actionMessages as …`.
  final String byNamespace = i18n.substring(i18n.indexOf('const byNamespace'));
  final Iterable<RegExpMatch> pairs = RegExp(
    r'^\s+(\w+): (\w+) as MessageTable',
    multiLine: true,
  ).allMatches(byNamespace.substring(0, byNamespace.indexOf('};')));

  for (final RegExpMatch pair in pairs) {
    final int start = i18n.indexOf(RegExp('export const ${pair.group(2)}: MessageTable<\\w+> = '));

    if (start == -1) {
      throw StateError('i18n.ts names ${pair.group(2)} and does not declare it');
    }

    final Map<String, Object> table = _TsObject(i18n, i18n.indexOf('{', start)).parse();
    english[pair.group(1)!] = table['']!;
  }

  final Map<String, String> files = <String, String>{
    'lib/src/internal/messages_en.dart':
        '''
// Generated by `tool/generate.dart` from `packages/react/src/internal/i18n.ts`.
// Do not edit by hand.

/// The English strings, built in: every namespace and every key, which every
/// other language is merged over.
library;

/// English, by namespace and key.
const Map<String, Map<String, String>> nebaEnglishMessages = ${_dartMap(english)};
''',
  };

  final List<String> exports = <String>[];
  final List<File> sources =
      Directory('$_react/locales')
          .listSync()
          .whereType<File>()
          .where((File file) => file.path.endsWith('.ts') && !file.path.endsWith('index.ts'))
          .toList()
        ..sort((File a, File b) => a.path.compareTo(b.path));

  for (final File source in sources) {
    final String text = source.readAsStringSync();
    final String tag = source.uri.pathSegments.last.replaceAll('.ts', '');
    final String name = tag.replaceAllMapped(
      RegExp(r'-(\w)'),
      (Match match) => match.group(1)!.toUpperCase(),
    );
    final String language =
        RegExp(r'^/\*\*\s*\n\s*\*\s*([^\n]+?)\.?\n').firstMatch(text)?.group(1) ?? tag;
    final int start = text.indexOf(RegExp(r': NebaLocale = '));

    if (start == -1) {
      throw StateError('${source.path} declares no NebaLocale');
    }

    final Map<String, Object> messages = _TsObject(text, text.indexOf('{', start)).parse();
    final String file = 'lib/src/locales/${tag.replaceAll('-', '_')}.dart';

    exports.add(file.replaceFirst('lib/', ''));
    files[file] =
        '''
// Generated by `tool/generate.dart` from `packages/react/src/locales/$tag.ts`.
// Do not edit by hand.

/// $language, for `registerNebaMessages`.
library;

import 'package:neba/src/internal/messages.dart';

/// $language. Register it once, before the widgets that speak it are built:
/// `registerNebaMessages('$tag', $name)`.
const NebaLocale $name = NebaLocale(${_dartMap(messages)});
''';
  }

  files['lib/src/locales/all.dart'] =
      '''
// Generated by `tool/generate.dart`. Do not edit by hand.

/// Every language, by tag, for the tests that read all of them. An app
/// registers the ones it speaks one by one, and leaves the rest out of its
/// build; nothing in `lib/` imports this.
library;

import 'package:neba/src/internal/messages.dart';
${sources.map((File source) => "import 'package:neba/src/locales/${source.uri.pathSegments.last.replaceAll('.ts', '').replaceAll('-', '_')}.dart';").join('\n')}

/// Every language, by the tag it registers under.
const Map<String, NebaLocale> nebaAllLocales = <String, NebaLocale>{
${sources.map((File source) {
        final String tag = source.uri.pathSegments.last.replaceAll('.ts', '');
        final String name = tag.replaceAllMapped(RegExp(r'-(\w)'), (Match m) => m.group(1)!.toUpperCase());

        return "  '$tag': $name,";
      }).join('\n')}
};
''';

  files['lib/locales.dart'] =
      '''
$_header
/// The languages Neba's widgets speak besides English, which is built in.
///
/// Each is a constant to register once, before the widgets that speak it are
/// built. A language that is never registered is never in the app.
///
/// ```dart
/// import 'package:neba/locales.dart';
///
/// void main() {
///   registerNebaMessages('ko', ko);
///   runApp(const App());
/// }
/// ```
library;

export 'src/internal/messages.dart' show NebaLocale, registerNebaMessages;
${exports.map((String path) => "export '$path';").join('\n')}
''';

  return files;
}

/// [value] as a Dart literal: a map of maps of strings.
String _dartMap(Map<String, Object> value) {
  final StringBuffer out = StringBuffer();
  final bool nested = value.values.every((Object entry) => entry is Map);

  out.write(nested ? '<String, Map<String, String>>{' : '<String, String>{');

  for (final MapEntry<String, Object> entry in value.entries) {
    final Object item = entry.value;
    final String rendered = item is Map<String, Object>
        ? _dartMap(item)
        : _dartString(item as String);

    out.write('${_dartString(entry.key)}: $rendered,');
  }

  out.write('}');

  return out.toString();
}

String _dartString(String value) {
  final String escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n');

  return "'$escaped'";
}

/// A TypeScript object literal of strings and nested objects, read from the
/// `{` at [_at] in [_source].
///
/// Enough of the grammar for the message tables and nothing more: comments,
/// identifier and quoted keys, single- and double-quoted strings with their
/// escapes, nested objects and trailing commas. Anything else is an error,
/// rather than a table read wrongly.
class _TsObject {
  _TsObject(this._source, this._at);

  final String _source;
  int _at;

  Map<String, Object> parse() {
    _expect('{');
    final Map<String, Object> result = <String, Object>{};

    while (true) {
      _skip();

      if (_source[_at] == '}') {
        _at++;

        return result;
      }

      final String key = _key();
      _skip();
      _expect(':');
      _skip();
      result[key] = _source[_at] == '{' ? parse() : _string();
      _skip();

      if (_source[_at] == ',') {
        _at++;
      }
    }
  }

  void _skip() {
    while (_at < _source.length) {
      if (_source.startsWith('//', _at)) {
        _at = _source.indexOf('\n', _at);
      } else if (_source.startsWith('/*', _at)) {
        _at = _source.indexOf('*/', _at) + 2;
      } else if (' \t\r\n'.contains(_source[_at])) {
        _at++;
      } else {
        return;
      }
    }
  }

  void _expect(String char) {
    if (_source[_at] != char) {
      throw FormatException('expected "$char"', _source, _at);
    }

    _at++;
  }

  String _key() {
    if (_source[_at] == "'" || _source[_at] == '"') {
      return _string();
    }

    final Match? match = RegExp(r'[A-Za-z_$][\w$]*').matchAsPrefix(_source, _at);

    if (match == null) {
      throw FormatException('expected a key', _source, _at);
    }

    _at = match.end;

    return match.group(0)!;
  }

  String _string() {
    final String quote = _source[_at];

    if (quote != "'" && quote != '"') {
      throw FormatException('expected a string', _source, _at);
    }

    _at++;
    final StringBuffer out = StringBuffer();

    while (_source[_at] != quote) {
      if (_source[_at] == r'\') {
        final String escaped = _source[_at + 1];

        if (escaped == 'u') {
          out.writeCharCode(int.parse(_source.substring(_at + 2, _at + 6), radix: 16));
          _at += 6;
          continue;
        }

        out.write(switch (escaped) {
          'n' => '\n',
          't' => '\t',
          _ => escaped,
        });
        _at += 2;
        continue;
      }

      out.write(_source[_at]);
      _at++;
    }

    _at++;

    return out.toString();
  }
}
